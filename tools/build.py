def main() -> int:
    parser = argparse.ArgumentParser(description="组装静态站点")
    parser.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = parser.parse_args()

    projects = json.loads((ROOT / "data" / "projects.json").read_text(encoding="utf-8"))["projects"]
    posts = json.loads((ROOT / "data" / "posts.json").read_text(encoding="utf-8"))["posts"]
    now = json.loads((ROOT / "data" / "now.json").read_text(encoding="utf-8"))
    validate(projects, posts, now)

    if args.check:
        stale = []
        i18n_path = JS_DIR / "i18n.js"
        strings = json.loads((ROOT / "data" / "i18n.json").read_text(encoding="utf-8"))
        source = i18n_path.read_text(encoding="utf-8")
        start = source.find(FALLBACK_BEGIN)
        end = source.find(FALLBACK_END)
        expected = (
            source[:start] + render_fallback_block(strings) + source[end + len(FALLBACK_END):]
            if start != -1 and end != -1
            else None
        )
        if expected != source:
            stale.append("js/i18n.js 的兜底文案与 data/i18n.json 不一致")

        written = build_all(asset_hashes()) + build_extra()
        for path, content in written:
            expected_text = (
                GENERATED_NOTE + "\n" + content
                if path.suffix == ".html"
                else content
            )
            if not path.exists() or path.read_text(encoding="utf-8") != expected_text:
                stale.append(path.relative_to(ROOT).as_posix())

        if stale:
            fail(
                "以下生成物与源码不一致，请跑 python tools/build.py：\n  "
                + "\n  ".join(stale)
            )
        print(f"build: 校验通过，{len(written)} 个产物均为最新")
        return 0

    sync_i18n_fallback()
    sync_js_versions()
    written = build_all(asset_hashes()) + build_extra()

    changed = []
    for path, content in written:
        payload = (GENERATED_NOTE + "\n" + content) if path.suffix == ".html" else content
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != payload:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(payload, encoding="utf-8", newline="\n")
            changed.append(path.relative_to(ROOT).as_posix())

    print(f"build: 生成 {len(written)} 个产物，更新 {len(changed)} 个")
    for name in changed:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
