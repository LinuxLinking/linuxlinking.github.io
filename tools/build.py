def blog_list_html(posts: list[dict], strings: dict) -> str:
    """博客列表页的条目行。"""
    if not posts:
        return (
            '<div class="blog-empty">'
            '<div class="blog-empty-glyph" aria-hidden="true">✦ ✦ ✦</div>'
            f'<h2>{pair(strings["zh"]["blog.empty"], strings["en"]["blog.empty"])}</h2>'
            f'<p>{pair(strings["zh"]["blog.emptyHint"], strings["en"]["blog.emptyHint"])}</p>'
            '<a class="btn" href="../">'
            f'{pair(strings["zh"]["blog.back"], strings["en"]["blog.back"])}</a>'
            "</div>"
        )
    ordered = sorted(posts, key=lambda p: str(p.get("date") or ""), reverse=True)
    rows = []
    for post in ordered:
        rows.append(
            f'<a class="post-row" href="{esc(post_href(post))}">'
            f'<span class="post-date">{esc(post.get("date") or "")}</span>'
            f'<h2 class="post-title">{pair(pick(post.get("title"), "zh"), pick(post.get("title"), "en"))}</h2>'
            f'<p class="post-sum">{pair(pick(post.get("summary"), "zh"), pick(post.get("summary"), "en"))}</p>'
            "</a>"
        )
    return "".join(rows)


def post_related_html(post: dict, project: dict | None, others: list[dict], strings: dict) -> str:
    """文章尾部的「继续读」：相关项目 + 其它文章，顺手把内链织密。"""
    items = []
    if project:
        items.append(
            f'<li><a class="post-related-link" href="../../projects/{esc(project["id"])}/">'
            f"{pair(pick(project.get('title'), 'zh'), pick(project.get('title'), 'en'))}"
            f'<span class="post-related-note">'
            f"{pair(pick(project.get('tagline'), 'zh'), pick(project.get('tagline'), 'en'))}"
            "</span></a></li>"
        )
    for other in others:
        items.append(
            f'<li><a class="post-related-link" href="../{esc(other["slug"])}/">'
            f"{pair(pick(other.get('title'), 'zh'), pick(other.get('title'), 'en'))}"
            f'<span class="post-related-note">{esc(other.get("date") or "")}</span>'
            "</a></li>"
        )
    if not items:
        return ""
    return (
        '<section class="post-related">'
        f'<p class="section-label">{pair(strings["zh"]["post.related"], strings["en"]["post.related"])}</p>'
        f'<ul class="post-related-list">{"".join(items)}</ul>'
        "</section>"
    )


def post_body_html(post: dict) -> tuple[str, dict, str]:
    """读 post.md，返回（正文 HTML, front matter, 导读）。

    同一个目录里放了 post.en.md 就把英文正文一起渲染出来，两种语言并排写进
    HTML，靠 html[lang] 切换 —— 跟全站的双语机制是同一套。
    """
    path = ROOT / "blog" / post["slug"] / "post.md"
    meta, body = markdown.split_front_matter(path.read_text(encoding="utf-8"))
    zh_html = markdown.render(body)

    en_path = ROOT / "blog" / post["slug"] / "post.en.md"
    if not en_path.exists():
        return zh_html, meta, meta.get("lede") or ""

    _, en_body = markdown.split_front_matter(en_path.read_text(encoding="utf-8"))
    en_html = markdown.render(en_body)
    both = (
        f'<div class="i18n-zh" lang="zh-CN">{zh_html}</div>'
        f'<div class="i18n-en" lang="en">{en_html}</div>'
    )
    return both, meta, meta.get("lede") or ""


def detail_body_html(
    project: dict,
    prev_id: str,
    next_id: str,
    related: list[dict],
    strings: dict,
) -> str:
    """项目详情页的整块内容，构建期渲染。"""
