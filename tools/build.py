def fail(message: str):
    print(f"build: {message}", file=sys.stderr)
    raise SystemExit(1)


def esc(value) -> str:
    """转义成可以放进 HTML 属性或文本节点的值。"""
    return html.escape(str(value if value is not None else ""), quote=True)


def pick(value, lang: str = "zh", default: str = "") -> str:
    """取双语字段的一种语言；缺这一种时退回另一种。"""
    if isinstance(value, dict):
        return value.get(lang) or value.get("zh") or value.get("en") or default
    return default if value is None else str(value)


def pair(zh: str, en: str) -> str:
    """一段内容的双语写法。

    两种语言都写进 HTML：默认露中文，切到英文时 CSS 换另一份。搜索引擎两种
    都读得到，切换语言也不用重新拉数据。
    """
    return (
        f'<span class="i18n-zh" lang="zh-CN">{esc(zh)}</span>'
        f'<span class="i18n-en" lang="en">{esc(en)}</span>'
    )


# ---------------------------------------------------------------- 模板解析


def strip_comments(text: str) -> str:
    """模板里的说明性注释不该出现在产物里。"""
    return COMMENT_RE.sub("", text)


def parse_page(source: str) -> tuple[dict[str, str], dict[str, str], str]:
    """拆出 meta、命名块与正文。

    meta 是扁平的 key: value 表；值可以跨行（续行不带冒号），
    这样 og:meta 那几行可以整块写在 meta 里。
    """
    meta: dict[str, str] = {}
    blocks: dict[str, str] = {}

    m = META_RE.search(source)
    if not m:
        fail("页面缺少 <!--meta --> 块")

    current: str | None = None
    for line in m.group(1).splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        kv = KEY_RE.match(stripped)
        if kv:
            current = kv.group(1)
            meta[current] = kv.group(2).strip()
        elif current is not None:
            meta[current] += "\n" + stripped

    def take_block(match: re.Match[str]) -> str:
        blocks[match.group(1)] = match.group(2).strip()
        return ""

    content = BLOCK_RE.sub(take_block, source)
    content = META_RE.sub("", content, count=1)
    return meta, blocks, strip_comments(content).strip()


def prefixes_for(out_path: str) -> tuple[str, str]:
    """产物所在层级的资源前缀与链接前缀。

    根目录页面用 ""（资源）与 "./"（链接）；blog/ 下逐层加 "../"。
    """
    depth = out_path.count("/")
    return "../" * depth, ("../" * depth if depth else "./")


def zh_text(value) -> str:
    """取中文文案。数据里是 {zh, en}，缺 zh 时退回 en。"""
    return pick(value, "zh")


def expand_i18n(page_html: str, strings: dict) -> str:
    """把带 data-i18n 的元素换成中英两份。

    元素内容必须是一段纯文本 —— 模板里没有嵌套标签的那种。
    """
    zh = strings.get("zh", {})
    en = strings.get("en", {})

    def repl(match: re.Match[str]) -> str:
        key = match.group(3)
        if key not in zh or key not in en:
            return match.group(0)
        return match.group(1) + pair(zh[key], en[key]) + match.group(5)

    return I18N_EL_RE.sub(repl, page_html)


def redirect_targets(projects: list[dict]) -> dict[str, str]:
    """旧的项目详情地址现在去哪：project.html?id=<slug> -> projects/<slug>/。"""
    targets: dict[str, str] = {}
    for project in projects:
        pid = project.get("id")
        if not pid:
            continue
        if project.get("kind") == "project":
            targets[pid] = f"projects/{pid}/"
        elif project.get("path"):
            targets[pid] = project["path"]
    return targets


def site_path_exists(target: str, project_ids: set[str]) -> bool:
    """站内路径是否存在。projects/<id>/ 是构建期生成的目录，先看 id 在不在项目表里。"""
    path = target.rstrip("/")
    if path.startswith("projects/"):
        parts = path.split("/")
        return len(parts) == 2 and parts[1] in project_ids
    return (ROOT / path).exists()


# ---------------------------------------------------------------- 缓存指纹


def content_hash(path: Path, _memo: dict | None = None, _stack: set | None = None) -> str:
    """文件内容指纹。

    本地 import 的指纹按「被依赖文件的真实哈希」算进去，所以改了一个模块，
    引用它的模块、引用它的页面，指纹都会跟着变。

    以前这里是把 ?v= 抹掉再算，于是引用方的指纹跟依赖方无关：依赖改了，
    页面上的 URL 不变，老访客的浏览器就一直用着旧模块的缓存，新版本送不到他们手里。
    文件里已经写着的旧指纹会被这一步替换掉，所以脚本依然可重复执行。
    """
    memo = {} if _memo is None else _memo
    stack = set() if _stack is None else _stack
    path = path.resolve()

    if path in memo:
        return memo[path]

    text = path.read_bytes().decode("utf-8", errors="replace")
    if path in stack:
        # 循环依赖兜底：按裸内容算，不展开
        return hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]
    stack.add(path)

    def repl(match: re.Match[str]) -> str:
        head, spec, tail = match.groups()
        clean = spec.split("?")[0]
        target = (path.parent / clean).resolve()
        try:
            target.relative_to(ROOT)
        except ValueError:
            return match.group(0)
        if not target.exists():
            return match.group(0)
        return f"{head}{clean}?v={content_hash(target, memo, stack)}{tail}"

    updated = LOCAL_IMPORT_RE.sub(repl, text)
    stack.discard(path)
    digest = hashlib.sha256(updated.encode("utf-8")).hexdigest()[:8]
    memo[path] = digest
    return digest


def asset_hashes() -> dict[str, str]:
    hashes: dict[str, str] = {}
    for path in sorted(CSS_DIR.glob("*.css")):
        hashes[f"css/{path.name}"] = content_hash(path)
    for path in sorted(JS_DIR.glob("*.js")):
        hashes[f"js/{path.name}"] = content_hash(path)
    return hashes


def rewrite_js_imports(hashes: dict[str, str]) -> list[Path]:
    """给 js 里指向本地模块的 import 加上指纹，避免模块改了但浏览器还用旧缓存。

    vendor/ 目录跳过：mermaid 体积大且极少变动，不值得让所有人重下。
    """
    touched: list[Path] = []
    for path in sorted(JS_DIR.glob("*.js")):
        source = path.read_text(encoding="utf-8")

        def add_version(match: re.Match[str]) -> str:
            head, spec, tail = match.groups()
            clean = spec.split("?")[0]
            target = (path.parent / clean).resolve()
            try:
                rel = target.relative_to(ROOT).as_posix()
            except ValueError:
                return match.group(0)
            version = hashes.get(rel)
            if not version:
                return match.group(0)
            return f"{head}{clean}?v={version}{tail}"

        updated = LOCAL_IMPORT_RE.sub(add_version, source)
        if updated != source:
            path.write_text(updated, encoding="utf-8", newline="\n")
            touched.append(path)
    return touched


def sync_js_versions() -> list[Path]:
    """把 import 指纹刷到稳定状态。

    某模块的指纹变了，导入它的模块内容也变了，它的指纹又变了 —— 逐轮推进直到不再变化。
    """
    touched: list[Path] = []
    for _ in range(6):
        rewritten = rewrite_js_imports(asset_hashes())
        if not rewritten:
            break
        touched.extend(rewritten)
    return touched


# ---------------------------------------------------------------- i18n 兜底文案

FALLBACK_BEGIN = "/* FALLBACK:BEGIN */"
FALLBACK_END = "/* FALLBACK:END */"


def render_fallback_block(strings: dict) -> str:
    """把 data/i18n.json 渲染成 i18n.js 里的 FALLBACK 常量。

    文案只维护一份：data/i18n.json。js/i18n.js 里的兜底副本由脚本生成，
    这样离线时看到的也是最新文案，而不是一份手抄的过期清单。
    """
    lines = [FALLBACK_BEGIN, "const FALLBACK = {"]
    for lang in sorted(strings):
        bucket = strings[lang]
        lines.append(f"  {lang}: {{")
        for key in sorted(bucket):
            value = json.dumps(bucket[key], ensure_ascii=False)
            lines.append(f"    {json.dumps(key, ensure_ascii=False)}: {value},")
        lines.append("  },")
    lines.append("};")
    lines.append(FALLBACK_END)
    return "\n".join(lines)


def sync_i18n_fallback() -> Path | None:
    """把 data/i18n.json 的内容写进 js/i18n.js 的 FALLBACK 块。"""
    strings = json.loads((ROOT / "data" / "i18n.json").read_text(encoding="utf-8"))
    path = JS_DIR / "i18n.js"
    source = path.read_text(encoding="utf-8")

    start = source.find(FALLBACK_BEGIN)
    end = source.find(FALLBACK_END)
    if start == -1 or end == -1:
        fail("js/i18n.js 缺少 FALLBACK:BEGIN / FALLBACK:END 标记")

    updated = source[:start] + render_fallback_block(strings) + source[end + len(FALLBACK_END):]
    if updated == source:
        return None

    path.write_text(updated, encoding="utf-8", newline="\n")
    return path


