#!/usr/bin/env python3
"""站点组装脚本：把 layouts/ + pages/ 组装成可直接发布的静态页面。

零依赖，只用标准库。用法：

    python tools/build.py            # 生成全部页面
    python tools/build.py --check    # 只校验，不写文件（CI 用）

做三件事：
1. 用 layouts/base.html 套 pages/*.html，生成根目录与 blog/ 下的 HTML。
2. 按 data/posts.json 生成每篇文章的 blog/<slug>/index.html。
3. 按文件内容 hash 给 css/js 引用加 ?v= 缓存指纹，并同步改写 js 内部的本地 import。
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYOUTS = ROOT / "layouts"
PAGES = ROOT / "pages"

GENERATED_NOTE = "<!-- generated by tools/build.py — edit pages/ and layouts/ instead -->"

# 页面清单：源码 -> 产物。产物所在层级决定资源前缀。
SITE_PAGES = [
    ("pages/index.html", "index.html"),
    ("pages/project.html", "project.html"),
    ("pages/blog.html", "blog/index.html"),
    ("pages/404.html", "404.html"),
]

# 博文壳：本身不产出文件，而是作为每篇文章的正文模板套进 base.html
POST_LAYOUT = "layouts/post.html"

META_RE = re.compile(r"^<!--meta\s*\n(.*?)^-->\s*$", re.S | re.M)
BLOCK_RE = re.compile(r"<!--block\s+(\w+)-->\s*(.*?)\s*<!--endblock(?:\s+\1)?-->", re.S)
COMMENT_RE = re.compile(r"<!--.*?-->", re.S)
KEY_RE = re.compile(r"^([A-Za-z][\w-]*)\s*:\s*(.*)$")
VERSION_QUERY_RE = re.compile(r"(\?v=)[0-9a-f]{8,}")
LOCAL_IMPORT_RE = re.compile(r"""(from\s+["']|import\s+["'])(\.\.?/[^"']+?)(["'])""")

CSS_DIR = ROOT / "css"
JS_DIR = ROOT / "js"


def fail(message: str):
    print(f"build: {message}", file=sys.stderr)
    raise SystemExit(1)


# ---------------------------------------------------------------- 模板解析


def strip_comments(text: str) -> str:
    """模板里的说明性注释不该出现在产物里。"""
    return COMMENT_RE.sub("", text)


def parse_page(source: str) -> tuple[dict[str, str], dict[str, str], str]:
    """拆出 meta、命名块与正文。

    meta 是扁平的 key: value 表；值可以跨行（续行不带冒号），
    这样 og:meta 那几行可以整块写在 meta 里。
    """
    meta: dict[str, str] = {}
    blocks: dict[str, str] = {}

    m = META_RE.search(source)
    if not m:
        fail("页面缺少 <!--meta --> 块")

    current: str | None = None
    for line in m.group(1).splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        kv = KEY_RE.match(stripped)
        if kv:
            current = kv.group(1)
            meta[current] = kv.group(2).strip()
        elif current is not None:
            meta[current] += "\n" + stripped

    def take_block(match: re.Match[str]) -> str:
        blocks[match.group(1)] = match.group(2).strip()
        return ""

    content = BLOCK_RE.sub(take_block, source)
    content = META_RE.sub("", content, count=1)
    return meta, blocks, strip_comments(content).strip()


def prefixes_for(out_path: str) -> tuple[str, str]:
    """产物所在层级的资源前缀与链接前缀。

    根目录页面用 ""（资源）与 "./"（链接）；blog/ 下逐层加 "../"。
    """
    depth = out_path.count("/")
    return "../" * depth, ("../" * depth if depth else "./")


# ---------------------------------------------------------------- 缓存指纹


def content_hash(path: Path) -> str:
    """文件内容指纹。计算前先抹掉已有的 ?v= 指纹，保证脚本可重复执行。"""
    text = path.read_bytes().decode("utf-8", errors="replace")
    stripped = VERSION_QUERY_RE.sub(r"\1", text)
    return hashlib.sha256(stripped.encode("utf-8")).hexdigest()[:8]


def asset_hashes() -> dict[str, str]:
    hashes: dict[str, str] = {}
    for path in sorted(CSS_DIR.glob("*.css")):
        hashes[f"css/{path.name}"] = content_hash(path)
    for path in sorted(JS_DIR.glob("*.js")):
        hashes[f"js/{path.name}"] = content_hash(path)
    return hashes


def rewrite_js_imports(hashes: dict[str, str]) -> list[Path]:
    """给 js 里指向本地模块的 import 加上指纹，避免模块改了但浏览器还用旧缓存。

    vendor/ 目录跳过：marked 与 mermaid 体积大且极少变动，不值得让所有人重下。
    """
    touched: list[Path] = []
    for path in sorted(JS_DIR.glob("*.js")):
        source = path.read_text(encoding="utf-8")

        def add_version(match: re.Match[str]) -> str:
            head, spec, tail = match.groups()
            clean = spec.split("?")[0]
            target = (path.parent / clean).resolve()
            try:
                rel = target.relative_to(ROOT).as_posix()
            except ValueError:
                return match.group(0)
            version = hashes.get(rel)
            if not version:
                return match.group(0)
            return f"{head}{clean}?v={version}{tail}"

        updated = LOCAL_IMPORT_RE.sub(add_version, source)
        if updated != source:
            path.write_text(updated, encoding="utf-8", newline="\n")
            touched.append(path)
    return touched


def sync_js_versions() -> list[Path]:
    """把 import 指纹刷到稳定状态。

    某模块的指纹变了，导入它的模块内容也变了，它的指纹又变了 —— 逐轮推进直到不再变化。
    """
    touched: list[Path] = []
    for _ in range(6):
        rewritten = rewrite_js_imports(asset_hashes())
        if not rewritten:
            break
        touched.extend(rewritten)
    return touched


# ---------------------------------------------------------------- 组装


def render(template: str, values: dict[str, str]) -> str:
    """替换占位符。

    反复替换直到没有占位符为止 —— 正文片段里也可能带占位符（如 {{link}}），
    单趟替换会因为插入顺序而漏掉它们。
    """
    out = template
    for _ in range(6):
        updated = out
        for key, value in values.items():
            updated = updated.replace("{{" + key + "}}", value)
        if updated == out:
            break
        out = updated
    return out


def build_page(
    shell: str,
    meta: dict[str, str],
    blocks: dict[str, str],
    content: str,
    out_path: str,
    hashes: dict[str, str],
) -> str:
    asset_prefix, link_prefix = prefixes_for(out_path)
    css_files = [f"css/{c.strip()}" for c in meta.get("css", "").split(",") if c.strip()]
    js_files = [f"js/{j.strip()}" for j in meta.get("js", "").split(",") if j.strip()]

    styles = "\n".join(
        f'<link rel="stylesheet" href="{asset_prefix}{name}?v={hashes[name]}">'
        for name in css_files
    )
    scripts = "\n".join(
        f'<script type="module" src="{asset_prefix}{name}?v={hashes[name]}"></script>'
        for name in js_files
    )

    values = {
        "lang": meta.get("lang", "zh-CN"),
        "title": meta.get("title", ""),
        "description": meta.get("description", ""),
        "bodyClass": meta.get("bodyClass", ""),
        "headExtra": meta.get("headExtra", ""),
        "asset": meta.get("assetPrefix", asset_prefix),
        "link": meta.get("linkPrefix", link_prefix),
        "styles": styles,
        "scripts": scripts,
        "viewSwitcher": blocks.get("viewSwitcher", ""),
        "topbarAction": blocks.get("topbarAction", ""),
        "pageDecor": blocks.get("pageDecor", ""),
        "content": content,
    }
    return render(shell, values)


def build_all(hashes: dict[str, str]) -> list[tuple[Path, str]]:
    shell = strip_comments((LAYOUTS / "base.html").read_text(encoding="utf-8"))
    post_layout = (ROOT / POST_LAYOUT).read_text(encoding="utf-8")
    posts = json.loads((ROOT / "data" / "posts.json").read_text(encoding="utf-8"))["posts"]

    written: list[tuple[Path, str]] = []

    for src, out in SITE_PAGES:
        source = (ROOT / src).read_text(encoding="utf-8")
        meta, blocks, content = parse_page(source)
        written.append((ROOT / out, build_page(shell, meta, blocks, content, out, hashes)))

    for post in posts:
        out = f"blog/{post['slug']}/index.html"
        meta, blocks, content = parse_page(post_layout)
        written.append((ROOT / out, build_page(shell, meta, blocks, content, out, hashes)))

    return written


# ---------------------------------------------------------------- 校验


def validate(projects: list[dict], posts: list[dict]) -> None:
    ids = [p.get("id") for p in projects]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        fail(f"projects.json 有重复 id: {sorted(dupes)}")

    for project in projects:
        for link in project.get("links") or []:
            href = link.get("href", "")
            if href.startswith(("http://", "https://")):
                continue
            if not (ROOT / href).exists():
                fail(f"项目 {project['id']} 的链接指向不存在的路径: {href}")

    slugs = [p.get("slug") for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        fail(f"posts.json 有重复 slug: {sorted(dupes)}")

    for post in posts:
        slug = post["slug"]
        if not (ROOT / "blog" / slug / "post.md").exists():
            fail(f"文章 {slug} 缺少 blog/{slug}/post.md")
        url = post.get("url") or f"{slug}/"
        if not (ROOT / "blog" / url).is_dir():
            fail(f"文章 {slug} 的 url 指向不存在的目录: {url}")


# ---------------------------------------------------------------- 主流程


def main() -> int:
    parser = argparse.ArgumentParser(description="组装静态站点")
    parser.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = parser.parse_args()

    projects = json.loads((ROOT / "data" / "projects.json").read_text(encoding="utf-8"))["projects"]
    posts = json.loads((ROOT / "data" / "posts.json").read_text(encoding="utf-8"))["posts"]
    validate(projects, posts)

    if args.check:
        written = build_all(asset_hashes())
        stale = [
            path.relative_to(ROOT).as_posix()
            for path, html in written
            if not path.exists()
            or path.read_text(encoding="utf-8") != GENERATED_NOTE + "\n" + html
        ]
        if stale:
            fail(
                "以下生成物与源码不一致，请跑 python tools/build.py：\n  "
                + "\n  ".join(stale)
            )
        print(f"build: 校验通过，{len(written)} 个页面均为最新")
        return 0

    sync_js_versions()
    written = build_all(asset_hashes())

    changed = []
    for path, html in written:
        payload = GENERATED_NOTE + "\n" + html
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != payload:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(payload, encoding="utf-8", newline="\n")
            changed.append(path.relative_to(ROOT).as_posix())

    print(f"build: 生成 {len(written)} 个页面，更新 {len(changed)} 个")
    for name in changed:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
