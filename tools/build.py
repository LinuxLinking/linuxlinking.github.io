def render(template: str, values: dict[str, str]) -> str:
    """替换占位符。

    反复替换直到没有占位符为止 —— 正文片段里也可能带占位符（如 {{link}}），
    单趟替换会因为插入顺序而漏掉它们。
    """
    out = template
    for _ in range(6):
        updated = out
        for key, value in values.items():
            updated = updated.replace("{{" + key + "}}", value)
        if updated == out:
            break
        out = updated
    return out


def build_page(
    shell: str,
    meta: dict[str, str],
    blocks: dict[str, str],
    content: str,
    out_path: str,
    hashes: dict[str, str],
    extra: dict[str, str] | None = None,
) -> str:
    asset_prefix, link_prefix = prefixes_for(out_path)
    asset_prefix = meta.get("assetPrefix", asset_prefix)
    link_prefix = meta.get("linkPrefix", link_prefix)

    css_files = [f"css/{c.strip()}" for c in meta.get("css", "").split(",") if c.strip()]
    # xp.css 是全站外壳（壁纸、任务栏、IE 窗口），每页都要有，且放在最后覆盖页面样式。
    if "css/xp.css" not in css_files:
        css_files.append("css/xp.css")
    js_files = [f"js/{j.strip()}" for j in meta.get("js", "").split(",") if j.strip()]

    styles = "\n".join(
        f'<link rel="stylesheet" href="{asset_prefix}{name}?v={hashes[name]}">'
        for name in css_files
    )
    # site.js 是全站共用的启动脚本（语言切换、标题随语言变），每页都带。
    # site.js 管语言切换，xp.js 管桌面外壳与 IE 窗口 —— 每一页都要有。
    scripts = "\n".join(
        [
            f'<script type="module" src="{asset_prefix}js/site.js?v={hashes["js/site.js"]}"></script>',
            f'<script type="module" src="{asset_prefix}js/xp.js?v={hashes["js/xp.js"]}"></script>',
        ]
        + [f'<script type="module" src="{asset_prefix}{name}?v={hashes[name]}"></script>' for name in js_files]
    )

    # 每一页都落在 XP 桌面上，所以 body 一定要带上 xp。
    body_class = meta.get("bodyClass", "")
    if "xp" not in body_class.split():
        body_class = f"xp {body_class}".strip()

    values = {
        "lang": meta.get("lang", "zh-CN"),
        "title": meta.get("title", ""),
        "description": meta.get("description", ""),
        "titleZh": meta.get("title", ""),
        "titleEn": meta.get("title", ""),
        "descZh": meta.get("description", ""),
        "descEn": meta.get("description", ""),
        "bodyClass": body_class,
        "headExtra": meta.get("headExtra", ""),
        "seoHead": "",
        "asset": asset_prefix,
        "link": link_prefix,
        "styles": styles,
        "scripts": scripts,
        "content": content,
        "overlay": blocks.get("overlay", ""),
    }
    values.update(extra or {})
    return render(shell, values)


