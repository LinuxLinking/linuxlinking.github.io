def sitemap_xml(projects: list[dict], posts: list[dict]) -> str:
    """sitemap.xml：把能被搜到的页面全列出来。

    soul-for-u/ 是写给一个人的小房间，不进 sitemap。
    """
    urls = [(f"{SITE_ORIGIN}/", "weekly", "1.0"), (f"{SITE_ORIGIN}/blog/", "weekly", "0.8")]
    for post in posts:
        urls.append((f"{SITE_ORIGIN}/blog/{post_href(post)}", "monthly", "0.7"))
    for project in projects:
        urls.append((f"{SITE_ORIGIN}/projects/{project['id']}/", "monthly", "0.9"))

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        GENERATED_NOTE_XML,
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]
    for loc, changefreq, priority in urls:
        lines.append(
            f"  <url><loc>{esc(loc)}</loc>"
            f"<changefreq>{changefreq}</changefreq>"
            f"<priority>{priority}</priority></url>"
        )
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


def robots_txt() -> str:
    """robots.txt。

    旧地址 /project.html 不挡：爬虫得能进去，才会跟着跳到项目的新地址。
    那一页自带 noindex,follow，不会自己被索引，权重却能顺着链接流过去。
    """
    return (
        f"{GENERATED_NOTE_XML}\n"
        "User-agent: *\n"
        "Allow: /\n"
        "\n"
        f"Sitemap: {SITE_ORIGIN}/sitemap.xml\n"
    )


def build_extra() -> list[tuple[Path, str]]:
    projects = json.loads((ROOT / "data" / "projects.json").read_text(encoding="utf-8"))["projects"]
    posts = json.loads((ROOT / "data" / "posts.json").read_text(encoding="utf-8"))["posts"]
    ordered = sorted(
        (p for p in projects if p.get("kind") == "project"),
        key=lambda p: p.get("order") or 0,
    )
    return [
        (ROOT / "sitemap.xml", sitemap_xml(ordered, posts)),
        (ROOT / "robots.txt", robots_txt()),
    ]


# ---------------------------------------------------------------- 校验


def validate(projects: list[dict], posts: list[dict], now: dict | None = None) -> None:
    if not (ROOT / "assets" / "og.png").exists():
        fail("assets/og.png 不存在，跑 python tools/og_image.py 生成")

    ids = [p.get("id") for p in projects]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        fail(f"projects.json 有重复 id: {sorted(dupes)}")

    for project in projects:
        pid = project.get("id") or ""
        if project.get("kind") == "project" and not re.fullmatch(r"[a-z0-9][a-z0-9-]*", pid):
            fail(f"项目 id 不能做目录名: {pid}")
        if project.get("kind") == "project" and not project.get("keywords"):
            fail(f"项目 {pid} 缺少 keywords（曝光要用）")

    for project in projects:
        for link in project.get("links") or []:
            href = link.get("href", "")
            if href.startswith(("http://", "https://")):
                continue
            if not (ROOT / href).exists():
                fail(f"项目 {project['id']} 的链接指向不存在的路径: {href}")

    slugs = [p.get("slug") for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        fail(f"posts.json 有重复 slug: {sorted(dupes)}")

    for post in posts:
        slug = post["slug"]
        if not (ROOT / "blog" / slug / "post.md").exists():
            fail(f"文章 {slug} 缺少 blog/{slug}/post.md")
        url = post.get("url") or f"{slug}/"
        if not (ROOT / "blog" / url).is_dir():
            fail(f"文章 {slug} 的 url 指向不存在的目录: {url}")

    project_ids = {p.get("id") for p in projects}

    for post in posts:
        slug = post.get("slug")
        pid = post.get("projectId")
        if pid and pid not in project_ids:
            fail(f"文章 {slug} 的 projectId 指向不存在的项目: {pid}")
        if not post.get("label"):
            fail(f"文章 {slug} 缺少 label（图纸节点标签用）")
        if not post.get("monogram"):
            fail(f"文章 {slug} 缺少 monogram（图纸节点字形用）")

    if now is not None:
        for lang, bucket in (now.get("now") or {}).items():
            items = bucket.get("items") or []
            if not items:
                fail(f"now.json 的 {lang} 分支没有条目")
            for item in items:
                href = item.get("href")
                if not href:
                    continue
                target = href.split("?", 1)[0]
                if not site_path_exists(target, project_ids):
                    fail(f"now.json 的 {lang} 条目指向不存在的路径: {href}")
        zh_items = len((now.get("now") or {}).get("zh", {}).get("items") or [])
        en_items = len((now.get("now") or {}).get("en", {}).get("items") or [])
        if zh_items != en_items:
            fail(f"now.json 的中英条目数不一致: zh {zh_items} / en {en_items}")


