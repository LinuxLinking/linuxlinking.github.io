def seo_head(
    url: str,
    title: str,
    description: str,
    *,
    og_type: str = "website",
    jsonld: dict | None = None,
    noindex: bool = False,
) -> str:
    """canonical、Open Graph、Twitter Card、结构化数据。

    社交平台不执行 JS，所以这些必须是构建期写死的静态标记。
    """
    lines = [f'<link rel="canonical" href="{esc(url)}">']
    if noindex:
        lines.append('<meta name="robots" content="noindex,follow">')
    lines += [
        f'<meta property="og:type" content="{og_type}">',
        f'<meta property="og:site_name" content="{esc(SITE_NAME)}">',
        f'<meta property="og:title" content="{esc(title)}">',
        f'<meta property="og:description" content="{esc(description)}">',
        f'<meta property="og:url" content="{esc(url)}">',
        f'<meta property="og:image" content="{esc(OG_IMAGE)}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        '<meta property="og:locale" content="zh_CN">',
        '<meta property="og:locale:alternate" content="en_US">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{esc(title)}">',
        f'<meta name="twitter:description" content="{esc(description)}">',
        f'<meta name="twitter:image" content="{esc(OG_IMAGE)}">',
    ]
    if jsonld:
        payload = json.dumps(jsonld, ensure_ascii=False).replace("</", "<\\/")
        lines.append(f'<script type="application/ld+json">{payload}</script>')
    return "\n".join(lines)


