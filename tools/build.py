META_RE = re.compile(r"^<!--meta\s*\n(.*?)^-->\s*$", re.S | re.M)
BLOCK_RE = re.compile(r"<!--block\s+(\w+)-->\s*(.*?)\s*<!--endblock(?:\s+\1)?-->", re.S)
COMMENT_RE = re.compile(r"<!--.*?-->", re.S)
KEY_RE = re.compile(r"^([A-Za-z][\w-]*)\s*:\s*(.*)$")
# 本地模块引用：静态 import、from ... import，以及 import("...") 动态引入。
