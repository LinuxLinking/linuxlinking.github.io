def summarize(text: str, limit: int = 96) -> str:
    """摘要太长时取第一句，作为一行预览。"""
    clean = " ".join(str(text or "").split())
    if not clean:
        return ""
    stop = next((clean.find(ch) for ch in "。.!?！？" if clean.find(ch) > 0), -1)
    first = clean[:stop] if stop > 0 else clean
    return first if len(first) <= limit else first[: limit - 1] + "…"


def site_path(out_path: str) -> str:
    """产物在站点里的地址：地址栏显示这个，根路径相对也认得。"""
    if out_path == "index.html":
        return "/"
    if out_path.endswith("/index.html"):
        return "/" + out_path[: -len("index.html")]
    return "/" + out_path


